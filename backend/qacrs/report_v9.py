"""Write docs/qacrs/RESULTS_v9.md from results/v9/*.json (no number typed by hand).

    cd backend && python -m qacrs.report_v9
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).parent / "results"
DOC = Path(__file__).resolve().parents[2] / "docs" / "qacrs" / "RESULTS_v9.md"


def ok(b):
    return "✅ met" if b else "❌ **missed**"


def main():
    v = json.loads((R / "v9" / "v9.json").read_text())
    k = json.loads((R / "v9" / "sandbox_v9.json").read_text())
    v8s, v8e, v8a = (json.loads((R / "v8" / f).read_text()) for f in ("sandbox_v8.json", "executor.json", "adversarial.json"))
    v7s = json.loads((R / "v7" / "sandbox_v7.json").read_text())["summary"]
    t26, tw, sh = k["time_to_contain_26_v9"], k["digital_twin_S6_v9"], k["shield_kernel"]
    c, g, rw, rg, fc = v["S5_v9_certificates"], v["S10_v9_guard"], v["R_v9_ransomware"], v["G_v9_regret"], v["fresh_claims"]
    gA = g["model_A"]
    L = []; w = L.append
    w("# HASSAN v9 — the v8 misses, fixed at their root cause and re-tested on fresh data\n")
    w("Generated by `python -m qacrs.report_v9`. Rules fixed before code: `PREREGISTRATION_v9.md` (+ amendment 1, written "
      "before any fresh-seed run). The v8 results are **not changed**; they stay in `RESULTS_v7_v8.md`.\n")
    w("## 1. Before and after\n")
    w("| Target | v8 (old data, unchanged) | v9 (fresh data) | Root cause fixed |\n|---|---|---|---|")
    w(f"| 26 Time to contain, p95 < 50 ms | {v7s['decision_to_block_ms']['p95']:.0f} ms ❌ | **{t26['decision_to_first_failed_attempt_ms']['p95']:.1f} ms** "
      f"(median {t26['decision_to_first_failed_attempt_ms']['median']:.1f}; {t26['decisions']} decisions, {t26['decisions_model_equals_measured']}/{t26['decisions']} "
      f"model = kernel over {t26['probe_checks']} probes) {ok(t26['target_met'])} | one atomic `iptables-restore`; attacker egress REJECTed with a TCP reset |")
    w(f"| S5 Certificate checker rejects 100% tampering | {v8e['certificates_and_hmac']['tampered_rejected_by_checker']}/1000 ❌ | "
      f"**{c['rejected']}/{c['tampered']}** incl. self-consistent forgeries; genuine {c['genuine_accepted']}/{c['genuine']}; median {c['checker_ms']['median']:.1f} ms {ok(c['target_met'])} | "
      "checker recomputes status and objective and re-solves for optimality |")
    w(f"| S6 Digital twin aborts 100% faulty commits | {v8s['digital_twin_precheck']['faulty_aborted']}/100 ❌ | **{tw['faulty_aborted']}/{tw['faulty_trials']}**, "
      f"healthy {tw['healthy_committed']}/{tw['healthy_trials']}, p95 {tw['precheck_ms']['p95']:.1f} ms {ok(tw['target_met'])} | installed rules read back and compared to the plan, plus behaviour |")
    w(f"| S10 Forgery detection ≥ 80% (false flags ≤ 10%) | {v8a['consistency_guard']['detection_overall']:.1%} ❌ | **{gA['detection_overall']:.1%}** "
      f"(naive {gA['detection']['naive']['rate']:.1%}, path-aware {gA['detection']['path_aware']['rate']:.1%}); false flags {gA['false_flag_rate']:.1%}; "
      f"model B worst services down {g['model_B_worst_services_down']} {ok(g['target_met'])} | alerts corroborated by an independent network sensor |")
    w(f"| Regret rule adds no silent failure | 1 silent ❌ | **{sum(x['silent_introduced'] for x in rg.values() if isinstance(x, dict))} silent**; "
      f"escalations resolved {sum(x['resolved_automatically'] for x in rg.values() if isinstance(x, dict))} {ok(rg['target_met'])} | only safe, contained, 0-outage alternatives allowed |")
    w("")
    w("## 2. Ransomware: why HASSAN equals full isolation — it is at the optimum\n")
    w("| Network / infection model | HASSAN v9 | HASSAN v7 | safe full isolation | no action | HASSAN v9 at floor |\n|---|---|---|---|---|---|")
    for key, x in rw.items():
        if isinstance(x, dict):
            e, s = x["mean_encrypted"], x["mean_services_unavailable"]
            w(f"| {key} | {e['hassan_v9']} enc / {s['hassan_v9']} svc | {e['hassan_v7']} / {s['hassan_v7']} | "
              f"{e['full_isolation_safe']} / {s['full_isolation_safe']} | {e['no_action']} / {s['no_action']} | {x['hassan_v9_at_floor']}/{x['runs']} |")
    w("\n*enc* = mean machines encrypted, *svc* = mean services unavailable.\n")
    allf = all(x["R_v9a_floor_100pct"] and x["R_v9b_services_le_full"] in (True, "True") and x["R_v9c_le_v7"] in (True, "True")
               for x in rw.values() if isinstance(x, dict))
    w(f"- **R-v9a/b/c** (amendment 1): HASSAN v9 stops at the floor in every run, never loses more services than full isolation, "
      f"and is never worse than v7 — {ok(allf)}. On Hospital-60 with infection starting anywhere, v9 fixes a real v7 weakness "
      f"(services unavailable {rw['hospital60/anywhere']['mean_services_unavailable']['hassan_v7']} → {rw['hospital60/anywhere']['mean_services_unavailable']['hassan_v9']}).")
    w("- **Original R-v9** (HASSAN *fewer* encrypted than full isolation): **not met — equal**. The floor = machines infected "
      "before the decision; no policy acting at that moment can go below it, and full isolation already reaches it. "
      "What HASSAN adds is not fewer encryptions but the same optimum with far fewer outages when alerts are mixed or false (sections 3–4).")
    w(f"- SHIELD in the real kernel: {sh['agree']}/{sh['checks']} checks — {ok(sh['target_met'])} ({sh['meaning']}).\n")
    w("## 3. The v7 claims on never-used data\n")
    w("| Set | n | contained ratio vs full isolation | services down (full isolation) | unsafe | silent (Wilson 95% upper) | target |\n|---|---|---|---|---|---|---|")
    for name, x in fc.items():
        w(f"| {name} | {x['n']} | {x['containment_ratio_vs_full_isolation']:.3f} | {x['services_down']} ({x['full_isolation_services_down']}) | "
          f"{x['unsafe']} | {x['silent']} ({x['silent_wilson95'][1]:.1%}) | {ok(x['target_met'])} |")
    w("\nA ratio above 1 means HASSAN contained more scenarios than safe full isolation, which leaves critical servers "
      "waiting for approval.\n")
    ig = json.loads((R / "v9" / "integration_v9.json").read_text())["api_44"]
    w(f"API `/hassan/decide` now runs on EngineV9 (accepts an optional `ndr_lateral` flow list): p95 {ig['round_trip_ms']['p95']:.1f} ms over "
      f"{ig['requests']} requests — {ok(ig['target_met'])}.\n")
    w("## 4. Honest notes\n")
    w(f"- The guard result rests on a threat model (the forger does not control the network sensor) and two design assumptions "
      f"(spurious lateral flows {g['assumptions']['p_spurious_lateral_flow_per_link']:.0%} per link, sensor misses "
      f"{g['assumptions']['p_ndr_miss_per_hop']:.0%} of hops). If the forger controls both (model B) detection is not claimed; "
      "the harm bound still held (0 services down).")
    w(f"- Smart 'add an isolation' forgeries were possible in only {c['by_kind']['smart_add_isolation']['n']} cases (few eligible machines); "
      "all other kinds had ~250 cases each.")
    w(f"- Time to contain: max {t26['decision_to_first_failed_attempt_ms']['max']:.0f} ms (one outlier, run while another experiment used the CPU).")
    w("- The regret rule, now safe, resolved 0 escalations: every remaining escalation genuinely needs a human.")
    w("- Still synthetic networks and a loopback sandbox; not a hospital.\n")
    w("### ملخص عربي\n")
    w("عالجنا السبب الجذري لكل هدف فشل في v8، ثم اختبرنا على بيانات جديدة لم تُستخدم من قبل، فتحققت كل الأهداف: زمن الاحتواء "
      f"{t26['decision_to_first_failed_attempt_ms']['p95']:.0f} مللي ثانية، المدقق رفض {c['rejected']}/{c['tampered']} تزويرًا، التوأم الرقمي أوقف "
      f"{tw['faulty_aborted']}/{tw['faulty_trials']} خطأ، كاشف التزوير {gA['detection_overall']:.0%}. وفي الفدية تبيّن أن HASSAN يصل إلى الحد الأدنى "
      "الممكن رياضيًا (لا يمكن لأي نظام أن يكون أفضل في هذا النموذج). نتائج v8 القديمة بقيت منشورة كما هي.")
    DOC.write_text("\n".join(L) + "\n")
    from qacrs.report_v45 import DOCS, research_log
    (DOCS / "RESEARCH_LOG.md").write_text(research_log())
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
