"""Build docs/qacrs/RESULTS_v6.md + fig6 from result files only, and refresh the research log.

    cd backend && python -m qacrs.report_v6
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from qacrs import figures_v3 as F
from qacrs import stats
from qacrs.report_v45 import DOCS, research_log

R = Path(__file__).parent / "results"
NAMES = (("full_isolation", "Full isolation"), ("full_isolation_safe", "Full isolation (safe)"),
         ("per_machine", "Per-machine rule"), ("q_acrs", "Q-ACRS + v5 gate"))


def j(p):
    return json.loads((R / p).read_text())


def pct(x):
    return f"{100 * x:.1f}%"


def fig_ood(rows):
    cats = [("CONTAINED", "Contained, fully automatic", F.GOOD), ("CONTAINED_PENDING_APPROVAL", "Contained after 2 approvers", "#7fcf7f"),
            ("ESCALATED", "Escalated to humans (action given)", F.WARN), ("NOT_CONTAINED", "Silent failure", F.SERIOUS),
            ("REJECTED", "Unsafe → rejected", F.CRIT)]
    n = len(rows)
    fig, ax = plt.subplots(figsize=(7.8, 3.8)); ax.set_axisbelow(True)
    for yi, (k, lab) in enumerate(NAMES):
        left = 0
        for key, _, col in cats:
            v = sum(r[k]["status"] == key for r in rows)
            if v:
                ax.barh(yi, v, left=left, color=col, edgecolor=F.SURFACE, linewidth=2, height=0.6)
                if v >= 12:
                    ax.text(left + v / 2, yi, str(v), ha="center", va="center", fontsize=8.5, color=F.INK)
            left += v
        ax.text(n * 1.02, yi, f"{sum(len(r[k]['services_down']) for r in rows)} services down", va="center", fontsize=8, color=F.INK2)
    ax.set_yticks(range(len(NAMES)), [l for _, l in NAMES]); ax.invert_yaxis()
    ax.set_xlim(0, n * 1.3); ax.grid(axis="y", visible=False); ax.set_xlabel(f"Scenarios (of {n})")
    ax.set_title("Out-of-distribution test: attack chains that follow the network")
    ax.legend([plt.Rectangle((0, 0), 1, 1, color=c) for _, _, c in cats], [l for _, l, _ in cats],
              loc="upper center", bbox_to_anchor=(0.45, -0.2), ncol=3, fontsize=7.5)
    F.foot(fig, f"Simulation, {n} attack-chain scenarios (seed 7007, never used before). Model frozen (LOCK_v5).", y=-0.2)
    F.save(fig, "fig6_ood.png")


def build() -> str:
    d, lat = j("v6/ood.json"), j("v6/latency.json")
    o, rows = d["ood"], d["rows"]; t = o["tests"]; g = o["gate_comparison_q_acrs"]; n = o["n"]
    L = ["# Q-ACRS — Results v6 (out-of-distribution, latency)", "",
         "> Generated by `python -m qacrs.report_v6` from `backend/qacrs/results/v6`. Criteria fixed in advance in "
         "`PREREGISTRATION_v6.md`. Model frozen (`LOCK_v5.json` checked before running). Simulation.", "",
         "## E11 — Attack chains (different generator, seed 7007)", "",
         f"{n} scenarios after dropping {len(d['meta']['settings']['dropped_duplicates'])} duplicates. Mean hacked machines "
         f"{d['chain_stats']['mean_hacked']:.2f}; two simultaneous chains in {pct(d['chain_stats']['two_chain_share'])}; "
         f"a chain reaches the database or domain controller in {pct(d['chain_stats']['reaches_critical'])}.", "",
         "| Method | Contained | …of which needs 2 approvers | Escalated | Silent | Rejected (unsafe) | Services down |",
         "|---|---|---|---|---|---|---|"]
    for k, lab in NAMES:
        st = [r[k]["status"] for r in rows]
        L.append(f"| {lab} | {st.count('CONTAINED') + st.count('CONTAINED_PENDING_APPROVAL')} | {st.count('CONTAINED_PENDING_APPROVAL')} | "
                 f"{st.count('ESCALATED')} | {st.count('NOT_CONTAINED')} | {st.count('REJECTED')} | "
                 f"{sum(len(r[k]['services_down']) for r in rows)} |")
    h1, h3, h4 = t["H1_v3"], t["H3_services_down_wilcoxon_one_sided"], t["H4_containment_mcnemar"]
    L += ["", "| Pre-registered hypothesis | Result | Verdict |", "|---|---|---|",
          f"| H2-v5-OOD (silent failures, Wilson upper ≤ 2%) | v3 gate {g['v3']['silent']} → v5 gate {g['v5']['silent']}/{n}, "
          f"CI {pct(g['v5']['silent_wilson95'][0])}–{pct(g['v5']['silent_wilson95'][1])} | {'supported' if o['H2_v5_supported'] else '**not supported**'} |",
          f"| H1-v3 (≥80% containment AND fewer services down) | ratio {h1['ratio']}; services {h1['q_services_down']} vs {h1['safe_full_services_down']} | "
          f"{'supported' if h1['supported'] else '**not supported**'} |",
          f"| H3 (fewer services down, Wilcoxon one-sided) | p = {h3['p']:.1e} | {'supported' if h3['supported'] else 'not supported'} |",
          f"| H4 (containment, exact McNemar) | Q-ACRS-only {h4['q_only_contained']} vs safe-full-only {h4['safe_full_only_contained']}, "
          f"p = {h4['p_two_sided']:.1e} | {h4['direction']} |",
          f"| Escalation rate (human workload) | {pct(g['v5']['escalation_rate'])} (Wilson {pct(g['v5']['escalation_wilson95'][0])}–"
          f"{pct(g['v5']['escalation_wilson95'][1])}) | reported, no threshold |", ""]
    esc_rules = {}
    for r in rows:
        if r["q_acrs"]["status"] == "ESCALATED":
            key = "+".join(sorted({e["rule"] for e in r["q_acrs"]["escalations"]}))
            esc_rules[key] = esc_rules.get(key, 0) + 1
    L += ["**Why H1 fails here:** attack chains often end on the database or domain controller. Q-ACRS never isolates a "
          "critical server by itself; it escalates (" + ", ".join(f"{k}: {v}" for k, v in sorted(esc_rules.items())) +
          " scenarios). Safe full isolation proposes isolating that server, which the pre-registered rule counts as "
          "\"contained, pending two-person approval\" — even though it also needs humans and takes the services down.", ""]
    # exploratory
    def counts(k):
        st = [r[k]["status"] for r in rows]
        return st.count("CONTAINED"), st.count("CONTAINED_PENDING_APPROVAL") + st.count("ESCALATED")
    qa, qh = counts("q_acrs"); ba, bh = counts("full_isolation_safe")
    qa_v = [r["q_acrs"]["status"] == "CONTAINED" for r in rows]; ba_v = [r["full_isolation_safe"]["status"] == "CONTAINED" for r in rows]
    q_only = sum(a and not b for a, b in zip(qa_v, ba_v)); b_only = sum(b and not a for a, b in zip(qa_v, ba_v))
    L += ["### Exploratory (NOT pre-registered): who needs a human?", "",
          "Counting only outcomes that need **no human at all**:", "",
          "| Method | Fully automatic containment | Needs a human (2 approvers or escalation) |", "|---|---|---|",
          f"| Q-ACRS + v5 gate | {qa} ({pct(qa / n)}, Wilson {pct(stats.wilson(qa, n)[0])}–{pct(stats.wilson(qa, n)[1])}) | {qh} |",
          f"| Full isolation (safe) | {ba} ({pct(ba / n)}, Wilson {pct(stats.wilson(ba, n)[0])}–{pct(stats.wilson(ba, n)[1])}) | {bh} |", "",
          f"Paired: Q-ACRS-only {q_only} vs safe-full-only {b_only} (exact McNemar p = {stats.mcnemar_exact(q_only, b_only):.1e}). "
          "This view was chosen after seeing the results, so it is a hypothesis for the next pre-registration, not a finding.", "",
          "![ood](figures/fig6_ood.png)", "",
          "## E12 — Decision latency (scenario → policy ready)", "",
          f"Machine: {lat['meta']['settings']['machine']}, {lat['meta']['settings']['cpu_count']} CPUs (this cloud container). "
          "Pipeline: reduced QUBO + exact solve + safety layer + v5 gate + executor plan (dry run). Median of 3 repetitions per scenario.", "",
          "| Set | Scenarios | Median (ms) | 95th percentile (ms) | Max (ms) |", "|---|---|---|---|---|"]
    for k, v in lat["sets"].items():
        L.append(f"| {k} | {v['n']} | {v['median_ms']:.2f} | {v['p95_ms']:.2f} | {v['max_ms']:.2f} |")
    L += ["", f"Target (p95 < 1000 ms and max < 7000 ms): **{'met' if lat['target_met'] else 'not met'}**. "
          "The quantum solver is not in this pipeline (exact classical solve); QAOA on hardware would add queue and run time.", ""]
    return "\n".join(L)


def main():
    d = j("v6/ood.json")
    fig_ood(d["rows"])
    (DOCS / "RESULTS_v6.md").write_text(build())
    (DOCS / "RESEARCH_LOG.md").write_text(research_log())
    print("Saved: docs/qacrs/RESULTS_v6.md, RESEARCH_LOG.md")


if __name__ == "__main__":
    main()
